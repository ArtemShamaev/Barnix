"""Generate apps/barnocraft_assets.h from the Barnocraft texture atlas.

The atlas is a 64x64 RGBA PNG of 4x4 16x16 tiles (see make_textures.py).
Each tile is stored with its mipmaps as 0xAARRGGBB. Barnix applications have
no FPU, so the sine table is 16.16 fixed point.
"""
import math
import pathlib
import struct
import sys
import zlib

TILES = 11


def decode_png(data):
    if data[:8] != b'\x89PNG\r\n\x1a\n':
        raise ValueError('not a PNG file')
    pos, idat, header = 8, b'', None
    while pos < len(data):
        length, kind = struct.unpack_from('>I4s', data, pos)
        body = data[pos + 8:pos + 8 + length]
        pos += 12 + length
        if kind == b'IHDR':
            header = struct.unpack('>IIBBBBB', body)
        elif kind == b'IDAT':
            idat += body
        elif kind == b'IEND':
            break
    width, height, depth, color, _, _, interlace = header
    if depth != 8 or color not in (2, 6) or interlace:
        raise ValueError('expected 8-bit RGB/RGBA non-interlaced PNG')
    channels = 4 if color == 6 else 3
    raw, stride = zlib.decompress(idat), width * channels
    rows, previous = [], bytearray(stride)
    for y in range(height):
        kind, line = raw[y * (stride + 1)], bytearray(raw[y * (stride + 1) + 1:(y + 1) * (stride + 1)])
        for i in range(stride):
            a = line[i - channels] if i >= channels else 0
            b, c = previous[i], previous[i - channels] if i >= channels else 0
            if kind == 1:
                line[i] = (line[i] + a) & 255
            elif kind == 2:
                line[i] = (line[i] + b) & 255
            elif kind == 3:
                line[i] = (line[i] + (a + b) // 2) & 255
            elif kind == 4:
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                line[i] = (line[i] + (a if pa <= pb and pa <= pc else b if pb <= pc else c)) & 255
        rows.append(line)
        previous = line
    pixels = []
    for line in rows:
        for x in range(width):
            p = line[x * channels:(x + 1) * channels]
            pixels.append(tuple(p) if channels == 4 else tuple(p) + (255,))
    return width, height, pixels


def mipmaps(tile):
    """16x16 ARGB texels -> levels 16, 8, 4, 2 and 1, alpha-weighted box filter.

    Distant faces sample a smaller level, so 16 texels never alias into noise
    inside one screen pixel."""
    levels, size, current = [tile], 16, tile
    while size > 1:
        size //= 2
        smaller = []
        for y in range(size):
            for x in range(size):
                quad = [current[(2 * y + j) * size * 2 + 2 * x + i] for j in (0, 1) for i in (0, 1)]
                alpha = sum(v >> 24 for v in quad)
                if alpha:
                    channel = [sum((v >> shift & 255) * (v >> 24) for v in quad) // alpha for shift in (16, 8, 0)]
                else:
                    channel = [0, 0, 0]
                smaller.append((alpha // 4) << 24 | channel[0] << 16 | channel[1] << 8 | channel[2])
        levels.append(smaller)
        current = smaller
    return [v for level in levels for v in level]


def main():
    source, output = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
    width, height, pixels = decode_png(source.read_bytes())
    if width != 64 or height != 64:
        raise ValueError('Barnocraft atlas must be 64x64 (4x4 tiles of 16x16)')
    texels = []
    for tile in range(TILES):
        ox, oy = tile % 4 * 16, tile // 4 * 16
        texels += mipmaps([(lambda r, g, b, a: a << 24 | r << 16 | g << 8 | b)(*pixels[(oy + y) * width + ox + x])
                           for y in range(16) for x in range(16)])
    sines = [round(math.sin(2 * math.pi * i / 4096) * 65536) for i in range(4096)]

    def table(kind, name, values, per_line, fmt):
        lines = [f'static const {kind} {name}[{len(values)}] = {{']
        for i in range(0, len(values), per_line):
            lines.append('    ' + ','.join(fmt(v) for v in values[i:i + per_line]) + ',')
        return lines + ['};']

    lines = [f'/* Generated by scripts/barnocraft_assets.py from {source.name}; do not edit. */',
             '#ifndef BARNOCRAFT_ASSETS_H', '#define BARNOCRAFT_ASSETS_H',
             f'#define BC_TILES {TILES}', '#define BC_TILE_TEXELS 341  /* mip levels 16, 8, 4, 2, 1 */']
    lines += table('unsigned int', 'bc_tex', texels, 8, lambda v: f'0x{v:08x}u')
    lines += table('int', 'bc_sin', sines, 16, str)
    lines.append('#endif')
    output.write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
