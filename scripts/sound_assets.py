"""Compress WAV clips into a C header for Barnix programs.

Usage: python3 scripts/sound_assets.py OUT.h PREFIX NAME=FILE.wav ...
The clips (22050 Hz 16-bit mono) become G.711 mu-law bytes. The header
numbers the clips PREFIX_NAME (in argument order) and gives PREFIX_COUNT,
PREFIX_TOTAL_FRAMES and the tables prefix_data[] and prefix_frames[];
decode them with bsnd_ulaw (BDK) or the kernel's copy of that decoder.
"""
import array
import pathlib
import sys
import wave

def encode(samples):
    """G.711 mu-law: 8 bits a sample, about 38 dB signal to noise."""
    out = bytearray()
    for sample in samples:
        sign = 0x80 if sample < 0 else 0
        magnitude = min(32635, -sample if sample < 0 else sample) + 0x84
        exponent = magnitude.bit_length() - 8
        mantissa = magnitude >> (exponent + 3) & 15
        out.append(~(sign | exponent << 4 | mantissa) & 255)
    return bytes(out)


def main():
    if len(sys.argv) < 4:
        sys.exit(__doc__)
    out, prefix = pathlib.Path(sys.argv[1]), sys.argv[2]
    lines = ['/* Generated by scripts/sound_assets.py from the sounds folder: do not edit. */', '#pragma once', '']
    names, frames = [], []
    for item in sys.argv[3:]:
        name, path = item.split('=', 1)
        with wave.open(path, 'rb') as f:
            if f.getnchannels() != 1 or f.getsampwidth() != 2 or f.getframerate() != 22050:
                sys.exit(f'{path}: expected 22050 Hz mono 16-bit')
            samples = array.array('h', f.readframes(f.getnframes()))
        data = encode(samples)
        lines.append(f'#define {prefix.upper()}_{name.upper()} {len(names)}')
        lines.append(f'static const unsigned char {prefix}_{name}[{len(data)}] = {{')
        for i in range(0, len(data), 24):
            lines.append(''.join(f'{b},' for b in data[i:i + 24]))
        lines.append('};')
        names.append(name)
        frames.append(len(samples))
    lines.append(f'#define {prefix.upper()}_COUNT {len(names)}')
    lines.append(f'#define {prefix.upper()}_TOTAL_FRAMES {sum(frames)}U')
    lines.append(f'static const unsigned char *const {prefix}_data[{len(names)}] = {{' +
                 ', '.join(f'{prefix}_{n}' for n in names) + '};')
    lines.append(f'static const unsigned int {prefix}_frames[{len(names)}] = {{' +
                 ', '.join(str(n) for n in frames) + '};')
    out.write_text('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
