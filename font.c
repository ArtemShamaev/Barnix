static unsigned char latin_row(unsigned int code, unsigned int row)
{
    static const unsigned char lower[26][7] = {
        {0,0,14,1,15,17,15},{16,16,30,17,17,17,30},{0,0,14,16,16,17,14},
        {1,1,15,17,17,17,15},{0,0,14,17,31,16,14},{6,9,8,28,8,8,8},
        {0,0,15,17,15,1,14},{16,16,30,17,17,17,17},{4,0,12,4,4,4,14},
        {2,0,6,2,2,18,12},{16,16,18,20,24,20,18},{12,4,4,4,4,4,14},
        {0,0,26,21,21,17,17},{0,0,30,17,17,17,17},{0,0,14,17,17,17,14},
        {0,0,30,17,30,16,16},{0,0,15,17,15,1,1},{0,0,22,25,16,16,16},
        {0,0,15,16,14,1,30},{8,8,28,8,8,9,6},{0,0,17,17,17,19,13},
        {0,0,17,17,17,10,4},{0,0,17,17,21,21,10},{0,0,17,10,4,10,17},
        {0,0,17,17,15,1,14},{0,0,31,2,4,8,31}
    };
    if (code >= 'a' && code <= 'z') return lower[code - 'a'][row] << 2;
    if (code >= 'A' && code <= 'Z') return latin[code - 'A'][row] << 2;
    if (code >= '0' && code <= '9') {
        static const unsigned char digits[10][7] = {
            {14,17,19,21,25,17,14},{4,12,4,4,4,4,14},{14,17,1,2,4,8,31},
            {30,1,1,14,1,1,30},{2,6,10,18,31,2,2},{31,16,30,1,1,17,14},
            {6,8,16,30,17,17,14},{31,1,2,4,8,8,8},{14,17,17,14,17,17,14},
            {14,17,17,15,1,2,28}
        };
        return digits[code - '0'][row] << 2;
    }
    switch (code) {
    case ' ': return 0;
    case '.': return row == 6 ? 12 : 0;
    case ',': return row == 6 ? 8 : row == 5 ? 4 : 0;
    case ':': return (row == 2 || row == 5) ? 12 : 0;
    case ';': return row == 2 ? 12 : row == 5 ? 8 : row == 6 ? 4 : 0;
    case '-': return row == 3 ? 28 : 0;
    case '_': return row == 6 ? 28 : 0;
    case '/': return (row == 0 || row == 6) ? 24 : 4 << (6 - row);
    case '\\': return (row == 0 || row == 6) ? 3 : 3 << row;
    case '(': return row < 2 ? 4 : row < 5 ? 8 : 4;
    case ')': return row < 2 ? 8 : row < 5 ? 4 : 8;
    case '[': return 28 | (row == 0 || row == 6 ? 3 : 0);
    case ']': return 28 | (row == 0 || row == 6 ? 24 : 0);
    case '+': return row == 3 ? 28 : row == 2 || row == 4 ? 4 : 0;
    case '=': return row == 2 || row == 4 ? 28 : 0;
    case '!': return row < 5 ? 4 : row == 6 ? 4 : 0;
    case '?': return row == 0 ? 28 : row == 1 ? 2 : row == 2 ? 4 : row == 3 ? 8 : row == 6 ? 4 : 0;
    case '>': return row == 1 || row == 5 ? 16 : row == 2 || row == 4 ? 8 : row == 3 ? 4 : 0;
    case '<': return row == 1 || row == 5 ? 2 : row == 2 || row == 4 ? 4 : row == 3 ? 8 : 0;
    case '$': return row == 0 || row == 6 ? 4 : row == 1 ? 14 : row == 2 ? 20 : row == 3 ? 12 : row == 4 ? 5 : row == 5 ? 14 : 0;
    case '%': return row == 0 ? 25 : row == 1 ? 9 : row == 2 ? 2 : row == 3 ? 4 : row == 4 ? 8 : row == 5 ? 18 : row == 6 ? 19 : 0;
    case '^': return row == 0 ? 4 : row == 1 ? 10 : 0;
    case '&': return row == 0 ? 12 : row == 1 ? 18 : row == 2 ? 12 : row == 3 ? 10 : row == 4 ? 17 : row == 5 ? 17 : row == 6 ? 14 : 0;
    case '*': return row == 1 ? 10 : row == 2 ? 4 : row == 3 ? 31 : row == 4 ? 4 : row == 5 ? 10 : 0;
    case '@': return row == 1 ? 14 : row == 2 ? 17 : row == 3 ? 23 : row == 4 ? 16 : row == 5 ? 15 : 0;
    case '|': return row < 7 ? 4 : 0;
    case '~': return row == 2 ? 10 : row == 3 ? 20 : 0;
    case '#': return (row == 1 || row == 5) ? 28 : row == 0 || row == 6 ? 10 : 10 | 4;
    case '"': return row == 0 ? 20 : 0;
    case '\'': return row == 0 ? 4 : 0;
    }
    return 0;
}
static void outb(unsigned short port, unsigned char value)
{ __asm__ volatile("outb %0, %1" : : "a"(value), "Nd"(port)); }
static unsigned char inb(unsigned short port)
{ unsigned char v; __asm__ volatile("inb %1, %0" : "=a"(v) : "Nd"(port)); return v; }
static unsigned char read_reg(unsigned short port, unsigned char index)
{ outb(port, index); return inb(port + 1); }
static void write_reg(unsigned short port, unsigned char index, unsigned char value)
{ outb(port, index); outb(port + 1, value); }
void console_font_init(void)
{
    unsigned char seq[5], gfx[9];
    for (int i = 0; i < 5; i++) seq[i] = read_reg(0x3c4, i);
    for (int i = 0; i < 9; i++) gfx[i] = read_reg(0x3ce, i);
    write_reg(0x3c4, 1, seq[1] | 0x20); /* screen off during plane access */
    write_reg(0x3c4, 2, 4); /* plane 2: character generator */
    write_reg(0x3c4, 4, 7); /* sequential addressing, no odd/even */
    write_reg(0x3ce, 1, 0);
    write_reg(0x3ce, 3, 0);
    write_reg(0x3ce, 4, 2);
    write_reg(0x3ce, 5, 0);
    write_reg(0x3ce, 6, 4); /* A0000, 64 KiB */
    write_reg(0x3ce, 8, 255);
    volatile unsigned char *font = (volatile unsigned char *)0xa0000;
    for (unsigned int i = 0; i < sizeof(glyphs)/sizeof(glyphs[0]); i++) {
        unsigned int base = text_glyph(glyphs[i].code) * 32;
        for (int y = 0; y < 32; y++) font[base + y] = 0;
        for (int y = 0; y < 7; y++) {
            unsigned char row = glyphs[i].rows[y] << 2;
            font[base + 1 + y * 2] = row;
            font[base + 2 + y * 2] = row;
        }
    }
    for (unsigned int c = 32; c < 127; c++) {
        unsigned int base = c * 32;
        for (int y = 0; y < 32; y++) font[base + y] = 0;
        for (int y = 0; y < 7; y++) {
            unsigned char row = latin_row(c, y);
            font[base + 1 + y * 2] = row;
            font[base + 2 + y * 2] = row;
        }
    }
    for (int i = 0; i < 9; i++) write_reg(0x3ce, i, gfx[i]);
    for (int i = 2; i < 5; i++) write_reg(0x3c4, i, seq[i]);
    write_reg(0x3c4, 1, seq[1]);
}
